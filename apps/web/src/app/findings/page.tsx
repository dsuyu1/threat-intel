export const runtime = "edge";

import Link from "next/link";
import { getDb, findings } from "@ti/db";
import { desc } from "drizzle-orm";
import { FindingCard } from "../../components/FindingCard";

async function getLatestFindings() {
  const db = getDb();
  return db
    .select()
    .from(findings)
    .orderBy(desc(findings.publishedAt))
    .limit(100);
}

export default async function FindingsPage() {
  const rows = await getLatestFindings();

  return (
    <div className="max-w-[90ch] mx-auto px-8 py-10 space-y-6">
      <header className="space-y-2">
        <h1 className="text-xl font-semibold text-zinc-100">Findings</h1>
        <p className="text-sm text-zinc-500">
          Latest CVEs, attacks, TTPs, exploit drops, and malware â€” generated by
          autonomous agents.
        </p>
      </header>

      <div className="space-y-3">
        {rows.map((finding) => (
          <Link
            key={finding.id}
            href={`/findings/${finding.id}`}
            className="block"
          >
            <FindingCard finding={finding} />
          </Link>
        ))}
      </div>
    </div>
  );
}

