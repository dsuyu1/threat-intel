export function iso2ToIsoNumeric(iso2: string): number | null {
  const k = iso2.trim().toUpperCase();
  return ISO2_TO_NUMERIC[k] ?? null;
}

export function isoNumericToIso2(numeric: number): string | null {
  return NUMERIC_TO_ISO2[numeric] ?? null;
}

export function isoNumericToRgb(numeric: number): { r: number; g: number; b: number } {
  const n = Math.max(0, Math.min(0xffffff, Math.floor(numeric)));
  return {
    r: (n >> 16) & 255,
    g: (n >> 8) & 255,
    b: n & 255,
  };
}

export function rgbToIsoNumeric(r: number, g: number, b: number): number {
  return ((r & 255) << 16) | ((g & 255) << 8) | (b & 255);
}
